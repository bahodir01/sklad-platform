"""Схемы М-AI «Семантический поиск товара для Telegram-бота» (спека15 §3a).

Не CRUD-модуль — своей таблицы нет, поэтому этот файл НЕ участвует в
табличном контракте 02-contract.json (в отличие от modules/*/schemas.py у
остальных модулей, где состав полей построчно сверяется с 02-contract.json).
``ProductMatch``/``ResolveResult`` — внутренние DTO сервисного слоя: их
потребитель — бот (следующий этап спеки), не отдельный публичный REST-эндпоинт.
"""

from typing import Literal

from pydantic import BaseModel


class ProductMatch(BaseModel):
    """Один товар-кандидат для inline-кнопки в боте.

    Намеренно только id+name (спека15 §3a: «ИИ только предлагает, не
    выбирает» — этого достаточно, чтобы отрисовать кнопку и сверить выбор
    учителя с реальным product_id при отправке заявки).
    """

    id: int
    name: str


class ResolveResult(BaseModel):
    """Итог шагов 1→2 поиска товара (спека15 §3a): подстрока → ИИ-поиск смысла.

    ``source`` — откуда взялись совпадения (бот использует для текста
    подсказки под кнопками). ``matches == []`` ⟺ шаги 1 и 2 не дали
    результата — бот должен предложить «Показать весь список»
    (шаг 3, ``service.find_all_paginated``, всегда доступен как альтернатива).
    """

    matches: list[ProductMatch]
    source: Literal["substring", "ai", "none"]
